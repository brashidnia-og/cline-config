#!/usr/bin/env bash
# Shared OpenCode install helpers for install-full.sh / install-lite.sh.
#
# OpenCode reads its global rules from a single AGENTS.md file
# (~/.config/opencode/AGENTS.md, falling back to ~/.claude/CLAUDE.md),
# while Cline reads a directory of per-file toggleable rule files. This
# library therefore generates AGENTS.md from the profile's .clinerules/
# at install time. Skills use the same SKILL.md format in both tools, so
# skill folders are copied verbatim into OpenCode's skills locations:
#
#   global:  ~/.config/opencode/AGENTS.md  +  ~/.config/opencode/skills/
#   project: <project>/AGENTS.md           +  <project>/.opencode/skills/
#
# Requires REPO_ROOT, die, info, sync_tree, install_hint from
# install-common.sh (sourced together by install_profile). Agents come from
# agents-common.sh (sourced by install_profile before these helpers run).

set -euo pipefail

# Substring of the first line of every generated AGENTS.md. Used to tell
# files we generated (safe to regenerate) from user-authored files (backed
# up before replacement).
AGENTS_MD_MARKER="cline-config:generated"

# OpenCode's global config dir. Defaults to ~/.config/opencode (honoring
# XDG_CONFIG_HOME when it is set); override with OPENCODE_CONFIG_DIR for
# non-standard setups.
resolve_opencode_global_dir() {
  printf '%s' "${OPENCODE_CONFIG_DIR:-${XDG_CONFIG_HOME:-${HOME}/.config}/opencode}"
}

# 0 if FILE exists and its first line carries the cline-config marker.
is_generated_agents_md() {
  local file="$1"
  [[ -f "$file" ]] || return 1
  local first_line
  first_line="$(head -n 1 "$file")"
  [[ "$first_line" == *"$AGENTS_MD_MARKER"* ]]
}

# Generate AGENTS.md from the profile's .clinerules/ into OUT_FILE.
# Rule files are concatenated in sorted order (top-level, then cmd/, then
# any other subdirectory). Files that are path-gated in Cline (paths:
# frontmatter) have the frontmatter stripped and are wrapped in a prose
# condition, because OpenCode has no path-gated rules.
generate_agents_md() {
  local profile_root="$1"
  local profile_name="$2"
  local out_file="$3"

  python3 - "$AGENTS_MD_MARKER" "$profile_root" "$profile_name" "$out_file" <<'PY'
import sys
from datetime import date
from pathlib import Path

marker = sys.argv[1]
profile_root = Path(sys.argv[2])
profile_name = sys.argv[3]
out_file = Path(sys.argv[4])
rules_dir = profile_root / ".clinerules"
if not rules_dir.is_dir():
    raise SystemExit(f"rules directory missing: {rules_dir}")

def ordered_rule_files():
    files = [p for p in rules_dir.iterdir() if p.is_file() and p.suffix in (".md", ".txt")]
    files.sort()
    for sub in sorted(p for p in rules_dir.iterdir() if p.is_dir()):
        files.extend(sorted(p for p in sub.iterdir() if p.is_file() and p.suffix in (".md", ".txt")))
    return files

def split_frontmatter(text):
    # (frontmatter_lines or None, body). Only a leading '---' block counts;
    # an unterminated block is treated as body (Cline behaves the same way).
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1:]).lstrip("\n")
    return None, text

def extract_paths(fm):
    if fm is None:
        return []
    paths = []
    in_paths = False
    for line in fm:
        s = line.strip()
        if s.startswith("paths:"):
            in_paths = True
            inline = s.split(":", 1)[1].strip()
            if inline:
                paths.append(inline.strip("'\""))
        elif in_paths:
            if s.startswith("- "):
                paths.append(s[2:].strip().strip("'\""))
            elif not s:
                continue
            elif s.startswith("#") or ":" in s:
                in_paths = False  # next key or a comment ends the list
    return paths

files = ordered_rule_files()
if not files:
    raise SystemExit(f"no rule files found under {rules_dir}")

parts = [
    f"<!-- {marker} profile={profile_name} on {date.today().isoformat()} -->",
    "",
    f"# Global rules — cline-config profile `{profile_name}`",
    "",
    "This file is generated by the cline-config installer from the profile's `.clinerules/` directory.",
    "It is the OpenCode counterpart of Cline's global rules: Cline reads a directory of",
    "per-file toggleable rule files, while OpenCode reads this single file.",
    "",
    "To change these rules, edit the profile in the cline-config repository and re-run the",
    "installer; manual edits here are overwritten on the next install.",
    "",
]

for rule in files:
    rel = rule.relative_to(rules_dir).as_posix()
    fm, body = split_frontmatter(rule.read_text(encoding="utf-8"))
    if fm is None:
        parts.append(f"<!-- source: {rel} -->")
        parts.append("")
        parts.append(body.rstrip("\n"))
        parts.append("")
        continue
    paths = extract_paths(fm)
    if paths:
        parts.append(f"<!-- source: {rel} — path-gated in Cline; stated as prose because OpenCode has no path-gated rules -->")
        parts.append("")
        parts.append(
            "> **Context-dependent section.** Apply the rules below only when the current work "
            "touches files, paths, or topics matching: "
            + ", ".join(f"`{p}`" for p in paths)
            + "."
        )
        parts.append("")
        parts.append(body.rstrip("\n"))
        parts.append("")
    else:
        parts.append(f"<!-- source: {rel} (Cline frontmatter stripped) -->")
        parts.append("")
        parts.append(body.rstrip("\n"))
        parts.append("")

out_file.write_text("\n".join(parts), encoding="utf-8")
print(f"  generated AGENTS.md from {len(files)} rule file(s), {len(''.join(parts))} bytes")
PY
}

# Validate skill folders against OpenCode's discovery rules (stricter than
# Cline's): frontmatter must have name (== directory name,
# ^[a-z0-9]+(-[a-z0-9]+)*$, <=64 chars) and description (<=1024 chars).
# Prints a report; exits 1 (aborting the install) on any violation.
validate_opencode_skills() {
  local skills_src="$1"
  python3 - "$skills_src" <<'PY'
import re
import sys
from pathlib import Path

skills_src = Path(sys.argv[1])
if not skills_src.is_dir():
    raise SystemExit(f"skills directory missing: {skills_src}")

name_re = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
BLOCK_SCALARS = {"|", "|-", "|+", ">", ">-", ">+"}
skills = sorted(p for p in skills_src.iterdir() if p.is_dir())

errors = []
for skill_dir in skills:
    name = skill_dir.name
    skill_md = skill_dir / "SKILL.md"
    if not skill_md.is_file():
        errors.append(f"{name}: missing SKILL.md")
        continue
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        errors.append(f"{name}: SKILL.md must start with a '---' YAML frontmatter block")
        continue
    close = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if close is None:
        errors.append(f"{name}: SKILL.md frontmatter is not closed (no second '---')")
        continue
    fm = lines[1:close]
    fm_name = None
    desc_parts = []
    in_desc = False
    for line in fm:
        if line[:1] in (" ", "\t"):
            if in_desc:
                desc_parts.append(line.strip())
            continue
        s = line.strip()
        if s.startswith("name:"):
            fm_name = s.split(":", 1)[1].strip().strip("'\"")
            in_desc = False
        elif s.startswith("description:"):
            in_desc = True
            val = s.split(":", 1)[1].strip()
            if val and val not in BLOCK_SCALARS:
                desc_parts.append(val)
        elif s:
            in_desc = False
    if fm_name is None:
        errors.append(f"{name}: frontmatter is missing 'name'")
    else:
        if fm_name != name:
            errors.append(f"{name}: frontmatter name '{fm_name}' does not match the directory name")
        if len(fm_name) > 64 or not name_re.match(fm_name):
            errors.append(f"{name}: name must match ^[a-z0-9]+(-[a-z0-9]+)*$ and be at most 64 chars (got '{fm_name}')")
    desc = " ".join(desc_parts)
    if not desc:
        errors.append(f"{name}: frontmatter is missing 'description'")
    elif len(desc) > 1024:
        errors.append(f"{name}: description is {len(desc)} chars (OpenCode limit is 1024)")

if errors:
    print("OpenCode skill validation failed:", file=sys.stderr)
    for e in errors:
        print(f"  - {e}", file=sys.stderr)
    raise SystemExit(1)
if skills:
    print(f"  {len(skills)} skill(s) valid for OpenCode discovery")
else:
    print("  no skill folders found (nothing to validate)")
PY
}

# OpenCode requires skill names to be unique across ALL discovery locations
# (unlike Cline, where a same-named global skill simply wins over a project
# one). Warn when a name we are installing also exists in the
# Claude-compatible locations OpenCode checks.
warn_claude_compatible_collisions() {
  local skills_src="$1"
  local compat_dir d name
  for compat_dir in "${HOME}/.claude/skills" "${HOME}/.agents/skills"; do
    [[ -d "$compat_dir" ]] || continue
    for d in "$skills_src"/*/; do
      [[ -d "$d" ]] || continue
      name="$(basename "$d")"
      if [[ -d "${compat_dir}/${name}" ]]; then
        info "  note: skill '${name}' also exists in ${compat_dir}. OpenCode requires unique skill names across locations; if it fails to load, remove one copy or set OPENCODE_DISABLE_CLAUDE_CODE_SKILLS=1."
      fi
    done
  done
}

# Install the OpenCode global targets: a generated AGENTS.md plus the
# profile's skills tree. A pre-existing AGENTS.md that does not carry the
# cline-config marker is backed up before replacement; a previously
# generated one is simply rewritten. The skills directory is replaced
# wholesale (same safety posture as the Cline side: switching full <-> lite
# must not leave stale skills behind).
install_opencode_global() {
  local profile_root="$1"
  local dry_run="${2:-0}"

  local oc_dir agents_dest skills_dest skills_src
  oc_dir="$(resolve_opencode_global_dir)"
  agents_dest="${oc_dir}/AGENTS.md"
  skills_dest="${oc_dir}/skills"
  skills_src="${profile_root}/.cline/skills"

  local profile_name agents_dir
  profile_name="$(basename "$profile_root")"
  agents_dir="${oc_dir}/agents"

  info "OpenCode global destinations:"
  info "  AGENTS.md: ${agents_dest} (generated from .clinerules/)"
  info "  Skills:    ${skills_dest}"
  info "  Agents:    ${agents_dir}"

  # Generating AGENTS.md needs python3. If it is missing we skip this step
  # (with a hint) so a Cline-only install still completes; a full install
  # will also fail later in the MCP gate, which has the same requirement.
  if ! command -v python3 >/dev/null 2>&1; then
    if [[ "$dry_run" == "1" ]]; then
      info "  note: python3 not found — AGENTS.md generation would be skipped (pass --skip-opencode to silence)"
      return
    fi
    info "python3 not found — skipping OpenCode install (Cline destinations above are unaffected)."
    install_hint python3
    info "Install python3 and re-run, or pass --skip-opencode."
    return
  fi

  # Validate before writing anything (this check is read-only).
  validate_opencode_skills "$skills_src"

  if [[ "$dry_run" == "1" ]]; then
    if [[ -f "$agents_dest" ]]; then
      if is_generated_agents_md "$agents_dest"; then
        info "  [dry-run] regenerate ${agents_dest} (previously generated by cline-config)"
      else
        info "  [dry-run] back up existing ${agents_dest}, then replace with the generated file"
      fi
    else
      info "  [dry-run] create ${agents_dest}"
    fi
    info "  [dry-run] replace skills in ${skills_dest}/"
    install_opencode_agents "$profile_name" "$agents_dir" 1
    return
  fi

  mkdir -p "$oc_dir"
  if [[ -f "$agents_dest" ]]; then
    if is_generated_agents_md "$agents_dest"; then
      info "AGENTS.md: regenerating previously generated file"
    else
      local bak="${agents_dest}.bak-$(date +%Y%m%d-%H%M%S)"
      cp -a "$agents_dest" "$bak"
      info "AGENTS.md: existing user file backed up to ${bak}; replacing with generated file"
    fi
  else
    info "AGENTS.md: creating ${agents_dest}"
  fi
  local tmp
  tmp="$(mktemp "${agents_dest}.XXXXXX")"
  generate_agents_md "$profile_root" "$profile_name" "$tmp"
  mv "$tmp" "$agents_dest"

  sync_tree "$skills_src" "$skills_dest" 0

  warn_claude_compatible_collisions "$skills_src"

  install_opencode_agents "$profile_name" "$agents_dir" 0

  info "OpenCode global install done."
}

# Install the OpenCode project targets: AGENTS.md at the project root plus
# .opencode/skills/. A pre-existing project AGENTS.md is NEVER overwritten
# unless --force was given (it is backed up first in that case). Project
# skills are skipped (with a note) when the same name already exists in the
# user's global OpenCode skills directory, because duplicate names break
# OpenCode skill discovery.
install_opencode_project() {
  local profile_root="$1"
  local project_dir="$2"
  local dry_run="${3:-0}"
  local force="${4:-0}"

  local oc_dir agents_dest skills_dest skills_src global_skills profile_name agents_dir
  oc_dir="$(resolve_opencode_global_dir)"
  agents_dest="${project_dir}/AGENTS.md"
  skills_dest="${project_dir}/.opencode/skills"
  skills_src="${profile_root}/.cline/skills"
  global_skills="${oc_dir}/skills"
  profile_name="$(basename "$profile_root")"
  agents_dir="${project_dir}/.opencode/agents"

  info "OpenCode project destinations:"
  info "  AGENTS.md: ${agents_dest}"
  info "  Skills:    ${skills_dest}"
  info "  Agents:    ${agents_dir}"

  if ! command -v python3 >/dev/null 2>&1; then
    if [[ "$dry_run" == "1" ]]; then
      info "  note: python3 not found — AGENTS.md generation would be skipped (pass --skip-opencode to silence)"
      return
    fi
    info "python3 not found — skipping OpenCode project install."
    install_hint python3
    info "Install python3 and re-run, or pass --skip-opencode."
    return
  fi

  validate_opencode_skills "$skills_src"

  if [[ "$dry_run" == "1" ]]; then
    if [[ -f "$agents_dest" ]]; then
      if [[ "$force" == "1" ]]; then
        info "  [dry-run] AGENTS.md: existing ${agents_dest} would be backed up and replaced"
      else
        info "  [dry-run] AGENTS.md: existing ${agents_dest} left untouched (use --force to replace)"
      fi
    else
      info "  [dry-run] create ${agents_dest}"
    fi
    info "  [dry-run] replace skills in ${skills_dest}/"
    install_opencode_agents "$profile_name" "$agents_dir" 1
    return
  fi

  if [[ -f "$agents_dest" ]]; then
    if [[ "$force" == "1" ]]; then
      local bak="${agents_dest}.bak-$(date +%Y%m%d-%H%M%S)"
      cp -a "$agents_dest" "$bak"
      info "AGENTS.md: existing file backed up to ${bak}; replacing with generated file"
    else
      info "AGENTS.md: ${agents_dest} already exists — left untouched (re-run with --force to replace)"
    fi
  else
    info "AGENTS.md: creating ${agents_dest}"
  fi

  # Regenerate unless the existing file was deliberately left untouched above.
  local will_write=1
  if [[ -f "$agents_dest" && "$force" != "1" ]]; then
    will_write=0
  fi
  if [[ "$will_write" == "1" ]]; then
    local tmp
    tmp="$(mktemp "${agents_dest}.XXXXXX")"
    generate_agents_md "$profile_root" "$(basename "$profile_root")" "$tmp"
    mv "$tmp" "$agents_dest"
  fi

  mkdir -p "$skills_dest"
  # Drop existing entries so switching full <-> lite leaves no stale skills.
  local e
  for e in "$skills_dest"/*; do
    [[ -e "$e" || -L "$e" ]] || continue
    rm -rf "$e"
  done

  local d name
  for d in "$skills_src"/*/; do
    [[ -d "$d" ]] || continue
    name="$(basename "$d")"
    if [[ -d "${global_skills}/${name}" ]]; then
      info "  skills: skipped '${name}' (already installed in ${global_skills}; duplicate names break OpenCode discovery)"
      continue
    fi
    cp -a "$d" "${skills_dest}/"
    info "  skills: copied ${name} -> ${skills_dest}/${name}"
  done

  warn_claude_compatible_collisions "$skills_src"

  install_opencode_agents "$profile_name" "$agents_dir" 0

  info "OpenCode project install done."
}